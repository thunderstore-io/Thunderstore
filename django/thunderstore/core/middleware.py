from django.conf import settings


class ContentLengthMiddleware:
    """
    Set Content-Length on non-streaming responses that don't have one.

    CommonMiddleware does this for most responses, but not for its own
    APPEND_SLASH redirect or for responses generated by the middleware
    around it. Must be the first entry in MIDDLEWARE to see all of them.
    """

    def __init__(self, get_response):
        self.get_response = get_response

    def __call__(self, request):
        response = self.get_response(request)
        if not response.streaming and not response.has_header("Content-Length"):
            response.headers["Content-Length"] = str(len(response.content))
        return response


class QueryCountHeaderMiddleware:
    def __init__(self, get_response):
        self.get_response = get_response

    def __call__(self, request):
        if not settings.DATABASE_QUERY_COUNT_HEADER:
            return self.get_response(request)
        else:
            from django.db import connection
            from django.test.utils import CaptureQueriesContext

            with CaptureQueriesContext(connection) as context:
                response = self.get_response(request)
            response["Django-Query-Count"] = len(context)
            return response
